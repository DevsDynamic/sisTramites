/*
|--------------------------------------------------------------------------
| Plugins
|--------------------------------------------------------------------------
|
| Adaptador para plugins JS.
| Si un campo pertenece a un plugin,
| aquí se actualiza su valor.
|
*/

export function setPluginValue(field, value) {
    /*
    |--------------------------------------------------------------------------
    | TomSelect
    |--------------------------------------------------------------------------
    */

    if (field.tomselect) {

        field.tomselect.setValue(value);

        return true;

    }

    /*
    |--------------------------------------------------------------------------
    | Select2
    |--------------------------------------------------------------------------
    */

    if (window.jQuery && $(field).hasClass('select2')) {

        $(field)
            .val(value)
            .trigger('change');

        return true;

    }

    /*
    |--------------------------------------------------------------------------
    | Choices.js
    |--------------------------------------------------------------------------
    */

    if (field.choices) {

        field.choices.setChoiceByValue(value);

        return true;

    }

    /*
    |--------------------------------------------------------------------------
    | Flatpickr
    |--------------------------------------------------------------------------
    */

    if (field._flatpickr) {

        field._flatpickr.setDate(value);

        return true;

    }

    /*
    |--------------------------------------------------------------------------
    | No plugin
    |--------------------------------------------------------------------------
    */

    return false;
}